def load_deck(path):
    src = open(path, encoding='utf-8').read()
    prefix = 'window.DECK = '
    assert src.startswith(prefix) and src.rstrip().endswith(';')
    return json.loads(src[len(prefix):].rstrip()[:-1])


def md_explanations(paths):
    """按题干收集 MD 题库的解析原文（deck 本就由这些 MD 生成，题干可精确匹配）"""
    qre = re.compile(r'^\*\*(?:\d+|A\d+)\.\*\*\s*(.+)$')
    ansre = re.compile(r'^\*\*答案：[A-D]\*\*(.*)$')
    tagre = re.compile(r'^((?:【[^】]*】)+)(.*)$')
    out = {}
    for p in paths:
        if not os.path.exists(p):
            continue
        lines = open(p, encoding='utf-8').read().split('\n')
        for i, ln in enumerate(lines):
            qm = qre.match(ln)
            if not qm:
                continue
            for j in range(i + 1, min(i + 8, len(lines))):
                am = ansre.match(lines[j])
                if am:
                    rest = am.group(1).strip()
                    tm = tagre.match(rest)
                    expl = (tm.group(2) if tm else rest).strip()
                    if expl:
                        out[qm.group(1).strip()] = expl
                    break
    return out


def glossary_terms(path):
    """解析 rpg/js/glossary.js → {术语名: d}"""
    src = open(path, encoding='utf-8').read()
    pat = re.compile(r"\{ id: '([^']+)', keys: \[.*?\], t: '([^']+)', en: '([^']*)', m: '([^']*)', d: '(.*?)' \},?$")
    out = {}
    for ln in src.split('\n'):
        m = pat.match(ln.strip())
        if m:
            out[m.group(2)] = m.group(5)
    return out


def main():
    ap = argparse.ArgumentParser(description='为 deck-data.js 全部题目补充 exp 解析字段')
    ap.add_argument('--dry-run', action='store_true', help='只校验统计，不写文件')
    args = ap.parse_args()

    data = load_deck(DECK)
    items = data['items']
    n0 = len(items)
    md = md_explanations(MD_SOURCES)
    glos = glossary_terms(GLOSSARY)
    print('素材：人工解析 %d 条 | MD 解析 %d 条 | 术语表 %d 条' % (len(EXP_HAND), len(md), len(glos)))

    used = {'hand': 0, 'md': 0, 'glossary': 0, 'keep': 0}
    problems = []
    for it in items:
        if it.get('exp'):
            used['keep'] += 1
            continue
        exp = EXP_HAND.get(it['id'])
        if exp:
            used['hand'] += 1
        else:
            exp = md.get(it['q'].strip())          # 兜底 1：题库 MD 解析原文
            if exp:
                used['md'] += 1
            else:                                   # 兜底 2：术语表 d（按考点名匹配）
                for t, d in glos.items():
                    if t in it['k'] or it['k'] in t:
                        exp = d
                        used['glossary'] += 1
                        break
        if not exp:
            problems.append('%s 无解析素材' % it['id'])
            continue
        # exp 插在 expl 之后，保持字段顺序整洁
        nit = {}
        for k, v in it.items():
            nit[k] = v
            if k == 'expl':
                nit['exp'] = exp
        if 'exp' not in nit:
            nit['exp'] = exp
        it.clear()
        it.update(nit)

    # ---- 校验：不通过就不写文件 ----
    missing = [it['id'] for it in items if not it.get('exp')]
    toolong = [it['id'] for it in items if it.get('exp') and len(it['exp']) > EXP_MAX]
    badfmt = [it['id'] for it in items
              if len(it['opts']) != 4 or len(set(it['opts'])) != 4 or not (0 <= it['ans'] <= 3)]
    assert not missing, '缺 exp: %s' % missing
    assert not toolong, 'exp 超 %d 字: %s -> %s' % (EXP_MAX, toolong, [items_map(items, i) for i in toolong])
    assert not badfmt, '题目格式异常: %s' % badfmt
    assert not problems, problems
    assert len(items) == n0, '题数被意外改动'

    print('题数: %d | exp 覆盖: %d | 来源: %s' % (len(items), sum(1 for i in items if i.get('exp')), used))
    if args.dry_run:
        print('dry-run：未写文件')
        return

    out = 'window.DECK = ' + json.dumps(data, ensure_ascii=False, indent=0) + ';'
    open(DECK, 'w', encoding='utf-8').write(out)
    print('已写回:', DECK, '(%.1f KB)' % (os.path.getsize(DECK) / 1024))


def items_map(items, qid):
    for it in items:
        if it['id'] == qid:
            return len(it['exp'])
    return -1


if __name__ == '__main__':
    main()
